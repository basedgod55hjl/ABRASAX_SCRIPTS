def seal_bytes(plaintext, name, prov):
    cek = rng(32)
    iv = rng(16)
    ct = aes_cbc_encrypt(cek, iv, plaintext)
    header = json.dumps({
        "v": 2, "magic": MAGIC.decode(), "name": name,
        "created": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "alg": "AES-256-CBC+HMAC-SHA256", "wrap": "RSA-2048 TPM-persisted",
        "provider": PROVIDER, "plaintext_bytes": len(plaintext),
        "ciphertext_bytes": len(ct),
    }, sort_keys=True).encode()

    key, how = get_or_create_key(prov, name)
    try:
        wrapped = rsa_pub_wrap(key, cek + iv)
    finally:
        ncrypt.NCryptFreeObject(key)

