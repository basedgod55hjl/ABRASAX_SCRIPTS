def get_or_create_key(prov, name):
    k = ctypes.c_void_p()
    if ncrypt.NCryptOpenKey(prov, ctypes.byref(k), name, 0, 0) == 0:
        return k, "existing"
    k = ctypes.c_void_p()
    s = ncrypt.NCryptCreatePersistedKey(prov, ctypes.byref(k), "RSA", name, 0, NCRYPT_OVERWRITE_KEY_FLAG)
    if s != 0:
        raise OSError(f"create key: {st(s)}")
    s = ncrypt.NCryptFinalizeKey(k, NCRYPT_SILENT_FLAG)
    if s != 0:
        raise OSError(f"finalize key: {st(s)}")
    return k, "created"


def rsa_pub_wrap(key, data):
    n = ctypes.c_ulong(0)
    s = ncrypt.NCryptEncrypt(key, data, len(data), None, None, ctypes.byref(n), 0)
    if s != 0:
        raise OSError(f"encrypt size: {st(s)}")
    buf = ctypes.create_string_buffer(n.value)
    s = ncrypt.NCryptEncrypt(key, data, len(data), None, buf, ctypes.byref(n), 0)
    if s != 0:
        raise OSError(f"encrypt: {st(s)}")
    return buf.raw[: n.value]


