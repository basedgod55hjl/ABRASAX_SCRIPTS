def rng(n):
    h = ctypes.c_void_p()
    if _bcrypt_rng.BCryptOpenAlgorithmProvider(ctypes.byref(h), "RNG", None, 0) != 0:
        raise OSError("open RNG")
    try:
        b = ctypes.create_string_buffer(n)
        if _bcrypt_rng.BCryptGenRandom(h, b, n, 0) != 0:
            raise OSError("BCryptGenRandom failed")
        return b.raw
    finally:
        _bcrypt_rng.BCryptCloseAlgorithmProvider(h, 0)


