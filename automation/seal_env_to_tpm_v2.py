def tree_digest(root):
    """SHA-256 chain over the sorted (relpath, sha256) list. Deterministic, and
    any add/remove/reorder changes the terminal digest."""
    acc = hashlib.sha256(b"")
    rows = []
    for dp, dns, fns in os.walk(root):
        dns.sort()
        for fn in sorted(fns):
            fp = os.path.join(dp, fn)
            h = hashlib.sha256(open(fp, "rb").read()).hexdigest()
            rel = os.path.relpath(fp, root).replace("\\", "/")
            acc = hashlib.sha256(acc.digest() + h.encode())
            rows.append({"rel": rel, "sha256": h, "bytes": os.path.getsize(fp)})
    return acc.hexdigest(), rows


