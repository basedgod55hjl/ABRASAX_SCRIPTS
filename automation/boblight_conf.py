"""Generate a boblight.conf for an Ambilight-style LED array.

This is the deterministic replacement for the Boblight Config Maker GUI: given
the panel geometry and how many LEDs sit on each edge, emit the [global],
[device] and [light] blocks with correct hscan/vscan percentages.

The thing that actually goes wrong in hand-written configs is ORDER: the
[light] blocks must be listed in exactly the physical wiring order of the LED
strip, because boblightd pushes one channel-triplet per light in sequence down
the serial link. A listed order that disagrees with the strip makes colours
land on the wrong edge. So this generator numbers lights along the strip
(starting top-left, clockwise) and makes that order explicit in a comment.

Usage:
    python boblight_conf.py --leds 25,14,25,14 --out boblight.conf
    python boblight_conf.py --leds 25,14,25,14 --port COM3 --serial
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path


def edges(counts: tuple[int, int, int, int], inset: float = 1.0) -> list[tuple[str, float, float]]:
    """Return (name, hscan_pct, vscan_pct) per LED, clockwise from top-left.

    hscan/vscan are the centre point of each LED's sample zone, which is what
    boblight uses (a single percentage pair, not a range, in the [light] block).
    """
    top, right, bottom, left = counts
    out: list[tuple[str, float, float]] = []

    for i in range(top):
        h = inset + (100 - 2 * inset) * (i + 0.5) / top
        out.append((f"top_{i + 1}", h, inset))
    for i in range(right):
        v = inset + (100 - 2 * inset) * (i + 0.5) / right
        out.append((f"right_{i + 1}", 100 - inset, v))
    for i in range(bottom):
        h = 100 - inset - (100 - 2 * inset) * (i + 0.5) / bottom
        out.append((f"bottom_{i + 1}", h, 100 - inset))
    for i in range(left):
        v = 100 - inset - (100 - 2 * inset) * (i + 0.5) / left
        out.append((f"left_{i + 1}", inset, v))
    return out


def render(counts, port="COM3", rate=25, inset=1.0) -> str:
    lights = edges(counts, inset)
    total = len(lights)
    L = [
        "# boblight.conf -- generated by ABRASAX SCRIPTS/automation/boblight_conf.py",
        f"# layout: {counts[0]} top, {counts[1]} right, {counts[2]} bottom,"
        f" {counts[3]} left  = {total} LEDs",
        "#",
        "# WIRING ORDER: lights are listed clockwise from the TOP-LEFT corner.",
        "# The physical strip MUST be wired in this same order, or colours land",
        "# on the wrong edge of the screen.",
        "",
        "[global]",
        "interface 127.0.0.1",
        "port 19333",
        f"channels 3",
        f"rate {rate}",
        "",
        "[device]",
        "name ambilight",
        "type momo",
        f"output {port}",
        "channels 3",
        "interval 20000",
        "",
    ]
    for idx, (name, h, v) in enumerate(lights, 1):
        base = (idx - 1) * 3
        L += [
            "[light]",
            f"name       {name}",
            f"color      red   Ambilight {base + 1}",
            f"color      green Ambilight {base + 2}",
            f"color      blue  Ambilight {base + 3}",
            f"hscan      {h:.2f} 0",
            f"vscan      {v:.2f} 0",
            "",
        ]
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--leds", default="25,14,25,14",
                    help="top,right,bottom,left LED counts (default 25,14,25,14 for 16:9)")
    ap.add_argument("--port", default="COM3", help="serial device for the Arduino")
    ap.add_argument("--rate", type=int, default=25)
    ap.add_argument("--inset", type=float, default=1.0, help="%% inset from screen edge")
    ap.add_argument("--out", default=None)
    args = ap.parse_args()

    counts = tuple(int(x) for x in args.leds.split(","))
    if len(counts) != 4 or any(c < 0 for c in counts) or sum(counts) == 0:
        print("--leds needs four non-negative integers: top,right,bottom,left", file=sys.stderr)
        return 2

    conf = render(counts, args.port, args.rate, args.inset)

    # self-check: every LED must sit inside 0..100 on both axes
    bad = [n for n, h, v in edges(counts, args.inset)
           if not (0 <= h <= 100 and 0 <= v <= 100)]
    if bad:
        print(f"FAILED bounds check: {bad}", file=sys.stderr)
        return 1

    if args.out:
        Path(args.out).write_text(conf, encoding="utf-8")
        print(f"wrote {args.out}: {sum(counts)} LEDs "
              f"({counts[0]}T {counts[1]}R {counts[2]}B {counts[3]}L)")
    else:
        print(conf)
    return 0


if __name__ == "__main__":
    sys.exit(main())
