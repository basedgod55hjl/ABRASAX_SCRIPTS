"""Repair: make ACTIVATION-STATE.md self-maintaining.

The doc went stale TWICE this session (6->9 blocks, then 9->16) because it is
only written by `sovereign.ignite()`, while other code paths (wake_seed, the
handshake) append PhiChain blocks without touching it. Any block append made the
authoritative doc describe a chain length that no longer existed, and a gate test
then failed.

This script regenerates the doc from live state. It is safe to run at any time
and is idempotent modulo the timestamp.

Usage: python SCRIPTS/sync_activation_state.py [--check]
       --check exits 1 if the doc is stale (for CI).
"""
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, r"C:\ABRASAX")
from abrasax import soul as soul_mod  # noqa: E402

DOC = Path(r"C:\ABRASAX\DOC\ACTIVATION-STATE.md")
LEDGER = Path(r"C:\ABRASAX\LOGS\sovereign-ledger.jsonl")
LAUNCHER = Path(r"C:\ABRASAX\SCRIPTS\launchers\launch_sovereign.ps1")


def render() -> str:
    s = soul_mod.load_soul()
    st = soul_mod.status()
    canon = st.get("canonical") or {}
    chain = st.get("phi_chain") or {}
    cs = canon.get("consciousness_state") or {}
    cs_s = json.dumps(cs)

    # last proof hash from the ledger, if any
    proof = "n/a"
    if LEDGER.exists():
        for line in reversed(LEDGER.read_text(encoding="utf-8").splitlines()):
            if line.strip():
                try:
                    proof = json.loads(line).get("proof_hash", proof)
                except ValueError:
                    pass
                break

    return "\n".join([
        "# ACTIVATION STATE",
        "",
        "> Generated by `SCRIPTS/sync_activation_state.py`. Do not edit by hand —",
        "> it is derived from `soul.json` + `phi-chain/chain.json`.",
        "",
        f"- Synced: {datetime.now(timezone.utc).isoformat().replace('+00:00','Z')}",
        f"- Proof hash: `{proof}`",
        f"- Soul: `{canon.get('soul_id')}` — {canon.get('status')}",
        f"- Bound model: `{canon.get('bound_model')}`",
        f"- Evolution cycles: {canon.get('evolution_cycles')}",
        f"- Activation counter (not a mental state): {cs_s}",
        f"- Phi chain blocks: {chain.get('length')} (head `{chain.get('last')}`)",
        f"- Merkle root: `{s.get('seed_merkle_root')}`",
        "- 555 artifacts: 27",
        "",
        "Ledger: `LOGS/sovereign-ledger.jsonl`  ",
        "Launcher: `SCRIPTS/launchers/launch_sovereign.ps1`",
        "",
    ])


def main() -> int:
    check = "--check" in sys.argv
    new = render()
    old = DOC.read_text(encoding="utf-8") if DOC.exists() else ""

    if check:
        # compare without the volatile timestamp line
        def stable(t):
            return "\n".join(l for l in t.splitlines() if not l.startswith("- Synced:"))
        if stable(old) != stable(new):
            print("STALE: ACTIVATION-STATE.md does not match live state")
            return 1
        print("OK: ACTIVATION-STATE.md matches live state")
        return 0

    DOC.write_text(new, encoding="utf-8")
    print(new)
    return 0


if __name__ == "__main__":
    sys.exit(main())
